"""
Симуляция ориентации спутника
==============================
Динамика вращения (Эйлер) + кинематика (кватернион) +
орбитальная механика + гравитационный градиентный момент.
ПИД-регулятор по кватерниону.

Зависимости: numpy, matplotlib
  pip install numpy matplotlib
"""

import math
import numpy as np
import matplotlib.pyplot as plt

# ═══════════════════════════════════════════════════════════════════════════
#  Константы
# ═══════════════════════════════════════════════════════════════════════════

MU_EARTH = 3.986004418e14   # гравитационный параметр Земли, м³/с²
RE       = 6_378_000.0      # радиус Земли, м

# ── Изменено: высота орбиты 400 км (было 500 км) ──────────────────────────
H_ORBIT  = 400_000.0        # высота орбиты, м

# ── Изменено: моменты инерции [100, 150, 200] кг·м² (было [100, 210, 70]) ─
J    = np.diag([100.0, 150.0, 200.0])
Jinv = np.diag([1/100.0, 1/150.0, 1/200.0])

# ═══════════════════════════════════════════════════════════════════════════
#  Физика
# ═══════════════════════════════════════════════════════════════════════════

def quat_to_rot_mat(q0, q1, q2, q3):
    return np.array([
        [q0*q0+q1*q1-q2*q2-q3*q3, 2*(q1*q2+q0*q3),          2*(q1*q3-q0*q2)         ],
        [2*(q1*q2-q0*q3),          q0*q0-q1*q1+q2*q2-q3*q3, 2*(q2*q3+q0*q1)         ],
        [2*(q1*q3+q0*q2),          2*(q2*q3-q0*q1),          q0*q0-q1*q1-q2*q2+q3*q3],
    ])


def grav_grad_torque(r, q0, q1, q2, q3):
    r_norm = np.linalg.norm(r)
    e_rb   = quat_to_rot_mat(q0, q1, q2, q3) @ (r / r_norm)
    k      = 3.0 * MU_EARTH / r_norm**3
    return k * np.cross(e_rb, J @ e_rb)


def right_part(x, Ms):
    dx           = np.zeros(13)
    w            = x[0:3]
    q0,q1,q2,q3 = x[3], x[4], x[5], x[6]
    r, v         = x[7:10], x[10:13]

    # Эйлер
    mgg     = grav_grad_torque(r, q0, q1, q2, q3)
    dx[0:3] = Jinv @ (Ms + mgg - np.cross(w, J @ w))

    # Кватернион
    wx, wy, wz = w
    dx[3] = 0.5 * (-q1*wx - q2*wy - q3*wz)
    dx[4] = 0.5 * ( q0*wx + q2*wz - q3*wy)
    dx[5] = 0.5 * ( q0*wy - q1*wz + q3*wx)
    dx[6] = 0.5 * ( q0*wz + q1*wy - q2*wx)

    # Орбита
    dx[7:10]  = v
    dx[10:13] = (-MU_EARTH / np.linalg.norm(r)**3) * r
    return dx


# ═══════════════════════════════════════════════════════════════════════════
#  RK4
# ═══════════════════════════════════════════════════════════════════════════

def rk4_step(f, x, h):
    k1 = f(x)
    k2 = f(x + h/2 * k1)
    k3 = f(x + h/2 * k2)
    k4 = f(x + h   * k3)
    return x + h/6 * (k1 + 2*k2 + 2*k3 + k4)


def normalize_q(x):
    x[3:7] /= np.linalg.norm(x[3:7])


# ═══════════════════════════════════════════════════════════════════════════
#  Симуляция
# ═══════════════════════════════════════════════════════════════════════════

def simulate():
    TO_RAD = math.pi / 180
    TO_DEG = 180 / math.pi

    r0  = RE + H_ORBIT
    v0  = math.sqrt(MU_EARTH / r0)
    inc = 51.6 * TO_RAD

    # ── Изменено: начальное отклонение 10° вокруг оси Z ──────────────────
    dev_half = 10.0 / 2.0 * TO_RAD      # половина угла → аргумент sin/cos
    q0_init  = math.cos(dev_half)        # ≈ 0.9962
    q3_init  = math.sin(dev_half)        # ≈ 0.0872

    # ── Изменено: начальная угловая скорость [0.3, -0.2, 0.1] °/с ────────
    x = np.array([
         0.3*TO_RAD, -0.2*TO_RAD,  0.1*TO_RAD,   # ω [рад/с]
         q0_init,    0.0,          0.0, q3_init,   # кватернион
         r0,         0.0,          0.0,            # r [м]
         0.0,        v0*math.cos(inc), v0*math.sin(inc),  # v [м/с]
    ])

    # ── Изменено: шаг 0.5 с, время 1000 с ────────────────────────────────
    t, tk, h = 0.0, 10_000.0, 0.05

    # ── Изменено: ПД → ПИД; Kp=15, Ki=0.001, Kw=10 ──────────────────────
    #    Kp  — пропорциональный (по вектору кватерниона [q1,q2,q3])
    #    Ki  — интегральный     (накопленная ошибка по кватерниону)
    #    Kw  — дифференциальный (по угловой скорости ω, аналог Kd)
    Kp, Ki, Kw = 15.0, 0.001, 10.0

    # Интегральный накопитель ошибки (вектор q1,q2,q3)
    q_integral = np.zeros(3)

    data = {k: [] for k in [
        "t",
        "w1", "w2", "w3",
        "q0", "q1", "q2", "q3",
        "rx", "ry", "rz",
        "vx", "vy", "vz",
        "alt", "speed",
        "mgg1", "mgg2", "mgg3",
        "Ms1",  "Ms2",  "Ms3",    # управляющий момент
        "qi1",  "qi2",  "qi3",    # интегральный накопитель
    ]}

    while t <= tk:
        q_vec = x[4:7]            # вектор-часть кватерниона [q1, q2, q3]
        omega = x[0:3]            # угловая скорость [рад/с]

        # ── ПИД закон управления ─────────────────────────────────────────
        #   Ms = -Kp·q_vec - Kw·ω - Ki·∫q_vec dt
        Ms = -Kp * q_vec - Kw * omega - Ki * q_integral

        mgg = grav_grad_torque(x[7:10], x[3], x[4], x[5], x[6])

        x = rk4_step(lambda s: right_part(s, Ms), x, h)
        normalize_q(x)

        # Обновление интегратора (метод прямоугольников, после шага)
        q_integral += x[4:7] * h

        t += h

        data["t"].append(t)
        data["w1"].append(x[0]*TO_DEG)
        data["w2"].append(x[1]*TO_DEG)
        data["w3"].append(x[2]*TO_DEG)
        data["q0"].append(x[3])
        data["q1"].append(x[4])
        data["q2"].append(x[5])
        data["q3"].append(x[6])
        data["rx"].append(x[7]/1e3)
        data["ry"].append(x[8]/1e3)
        data["rz"].append(x[9]/1e3)
        data["vx"].append(x[10])
        data["vy"].append(x[11])
        data["vz"].append(x[12])
        data["alt"].append((np.linalg.norm(x[7:10]) - RE) / 1e3)
        data["speed"].append(np.linalg.norm(x[10:13]))
        data["mgg1"].append(mgg[0])
        data["mgg2"].append(mgg[1])
        data["mgg3"].append(mgg[2])
        data["Ms1"].append(Ms[0])
        data["Ms2"].append(Ms[1])
        data["Ms3"].append(Ms[2])
        data["qi1"].append(q_integral[0])
        data["qi2"].append(q_integral[1])
        data["qi3"].append(q_integral[2])

    return {k: np.array(v) for k, v in data.items()}


